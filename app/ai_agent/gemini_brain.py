        f"• {cover_name}: {to_bn(cover_price)} টাকা\n"
        f"━━━━━━━━━━━━━━━━━━━━\n"
        f"👉 **মোট প্যাকেজ মূল্য:** প্রতি সেট **{to_bn(total_price)} টাকা** (১০০+ পিস অর্ডারের ক্ষেত্রে)।\n\n"
