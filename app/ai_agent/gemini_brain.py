def extract_order_quantity_number(text: str) -> Optional[int]:
    """
    Extracts order quantity integer from text supporting Bengali & English digits/words.
    Strictly ignores phone numbers, prices (টাকা/tk/৳), dates, and non-quantity digits.
    """
    if not text:
        return None
        
    # Ignore if text is or contains a phone number (e.g., 01929778281, 01816504097, +8801...)
    cleaned_digits_only = re.sub(r'\D', '', text)
    if len(cleaned_digits_only) >= 10:
        return None
    if re.search(r'(?:\+?880?1|01)[3-9]\d{8}', text):
        return None

    bengali_digits = {'০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4', '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9'}
    cleaned = ''
    for ch in text:
        cleaned += bengali_digits.get(ch, ch)
    cleaned_lower = cleaned.lower().strip()
    
    # Ignore if talking about money/prices without explicit quantity words
    if any(k in cleaned_lower for k in ["টাকা", "টাকার", "tk", "taka", "৳", "রেট", "মূল্য", "খরচ"]) and not any(k in cleaned_lower for k in ["পিস", "pcs", "টা", "টি", "কপি", "বানাবো"]):
        return None

    # Range pattern: e.g. "2-3 শত", "2-3 sho", "2-3শ", "200-300 পিস", "৫০-১০০ পিস"
    m_range_hundreds = re.search(r'(\d+)\s*[-/toথেকে]+\s*(\d+)\s*(?:শত|শ|sho|শো)', cleaned_lower)
    if m_range_hundreds:
        try:
            return int(m_range_hundreds.group(1)) * 100
        except Exception:
            pass

    m_range = re.search(r'(\d+)\s*[-/toথেকে]+\s*(\d+)\s*(?:পিস|পিসেস|টা|টি|pcs|pc|pieces|piece|কপি)?', cleaned_lower)
    if m_range:
        try:
            val = int(m_range.group(1))
            if 1 <= val <= 50000:
                return val
        except Exception:
            pass

    # Hundred multipliers: e.g. "5 শ", "5শ", "5 শত", "২ শত", "৩ শ", "5 sho"
    m_hundred = re.search(r'(\d+)\s*(?:শত|শ|sho|শো)\s*(?:পিস|পিসেস|টা|টি|pcs|pc|pieces|piece|কপি)?', cleaned_lower)
    if m_hundred:
        try:
            return int(m_hundred.group(1)) * 100
        except Exception:
            pass

    # Word based numbers in bengali
    bengali_words = [
        ('এক হাজার', 1000), ('হাজার', 1000), ('পাঁচশত', 500), ('পাঁচশ', 500),
        ('চারশত', 400), ('চারশ', 400),
        ('তিনশত', 300), ('তিনশ', 300), ('দুইশত', 200), ('দুইশ', 200),
        ('একশত', 100), ('একশ', 100), ('নব্বই', 90), ('আশি', 80), ('সত্তর', 70),
        ('ষাট', 60), ('পঞ্চাশ', 50), ('পঁঞ্চাশ', 50), ('চল্লিশ', 40),
        ('ত্রিশ', 30), ('তিরিশ', 30), ('পঁচিশ', 25), ('পচিশ', 25),
        ('বিশ', 20), ('কুড়ি', 20), ('পনেরো', 15), ('পনের', 15), ('দশ', 10), ('পাঁচ', 5)
    ]
    for word, val in bengali_words:
        if re.search(r'(?:^|\s)' + re.escape(word) + r'(?:\s|$|টা|টি|পিস|টি|পিসেস|pcs|ta|ti|কপি)', cleaned_lower):
            return val

    # Match explicit quantity units: e.g. "50 পিস", "100 pcs", "30 টা", "80 টি", "100 জন", "50 কপি"
    m_unit = re.search(r'(\d+)\s*(?:পিস|পিসেস|টা|টি|pcs|pc|pieces|piece|জন|কপি|set|সেট)', cleaned_lower)
    if m_unit:
        try:
            val = int(m_unit.group(1))
            if 1 <= val <= 50000:
                return val
        except Exception:
            pass

    # Match standalone digit only if it's a small standalone number (e.g. "50", "100", "30", "500") and NOT a phone or price
    if re.fullmatch(r'\d{1,5}', cleaned_lower):
        val = int(cleaned_lower)
        if 1 <= val <= 20000:
            return val

    return None

def analyze_conversation_history_context(conversation_history: list = None, current_message: str = "") -> dict:
    """
    Comprehensive Context & Memory Extractor for conversational continuity:
    - Extracts known order quantity (e.g. 100 pcs) from customer, bot, or admin turns across entire history
    - Detects what samples or package photos were ALREADY sent
    - Captures Human Admin / Shop Owner instructions and previous agreements
    - Prevents repeating questions, duplicate photo floods, and redundant sample prompts
    """
    context = {
        "known_quantity": None,
        "samples_already_sent": False,
        "packages_already_sent": False,
        "card_samples_sent": False,
        "fita_samples_sent": False,
        "cover_samples_sent": False,
        "owner_messages": [],
        "last_owner_instruction": "",
        "last_speaker": "none",
        "already_asked_quantity": False,
        "already_asked_sample_permission": False,
        "chosen_package": None,
        "institution_name": None,
        "history_summary_text": ""
    }

    if not conversation_history:
        curr_qty = extract_order_quantity_number(current_message)
        if curr_qty and curr_qty >= 1:
            context["known_quantity"] = curr_qty
        return context

    summary_lines = []

    for msg in conversation_history:
        sender_role = str(msg.get("sender_role") or msg.get("sender") or msg.get("sender_type") or msg.get("role") or "").lower()
        content = str(msg.get("content") or msg.get("text") or "").strip()
        media_url = str(msg.get("media_url") or msg.get("image_url") or "")
        
        c_low = content.lower()
        
        # Check media / images sent in history
        if media_url or any(ext in c_low for ext in [".jpg", ".png", ".jpeg", "/uploads/"]) or msg.get("has_images") or msg.get("has_media"):
            context["samples_already_sent"] = True
            m_low = (media_url or c_low).lower()
            if "package" in m_low or "wa000" in m_low or "প্যাকেজ" in c_low or "রেডি প্যাকেজ" in c_low:
                context["packages_already_sent"] = True
            if "card" in m_low or "কার্ড" in c_low:
                context["card_samples_sent"] = True
            if "fita" in m_low or "ribbon" in m_low or "ফিতা" in c_low:
                context["fita_samples_sent"] = True
            if "cover" in m_low or "holder" in m_low or "কভার" in c_low:
                context["cover_samples_sent"] = True

        # Check speaker turns
        if sender_role in ("admin", "owner", "main_admin", "seller"):
            if content:
                context["owner_messages"].append(content)
                context["last_owner_instruction"] = content
                context["last_speaker"] = "owner"
                summary_lines.append(f"• শপ ওনার / মূল অ্যাডমিন বলেছেন: \"{content}\"")
                owner_qty = extract_order_quantity_number(c_low)
                if owner_qty and owner_qty >= 1:
                    context["known_quantity"] = owner_qty
        elif sender_role in ("bot", "ai", "assistant"):
            context["last_speaker"] = "ai"
            if any(k in c_low for k in ["কত পিস বানাবেন", "কত পিস", "কতগুলো", "পরিমাণ কত", "কত পিস প্রয়োজন", "কত পিস লাগবে"]):
                context["already_asked_quantity"] = True
            if any(k in c_low for k in ["স্যাম্পল ছবিগুলো পাঠাবো", "ছবিগুলো পাঠাবো", "স্যাম্পল পাঠাব", "স্যাম্পল দেব"]):
                context["already_asked_sample_permission"] = True
            if any(k in c_low for k in ["প্যাকেজ ০১", "প্যাকেজ ০২", "প্যাকেজ ০৭", "রেডি প্যাকেজ", "১ থেকে ৭ সিরিয়াল"]):
                context["packages_already_sent"] = True
        else:
            context["last_speaker"] = "customer"
            q_val = extract_order_quantity_number(c_low)
            if q_val and q_val >= 1:
                context["known_quantity"] = q_val
                summary_lines.append(f"• কাস্টমার পরিমাণ জানিয়েছেন: {q_val} পিস")

            pkg_num = detect_specific_package_number(c_low)
            if pkg_num is not None:
                context["chosen_package"] = pkg_num
                summary_lines.append(f"• কাস্টমার প্যাকেজ পছন্দ করেছেন: প্যাকেজ ০{pkg_num}")

    curr_qty = extract_order_quantity_number(current_message)
    if curr_qty and curr_qty >= 1:
        context["known_quantity"] = curr_qty

    context["history_summary_text"] = "\n".join(summary_lines)
    return context

def get_id_card_sample_images(workspace_id: int = 1) -> list:
    """Returns all 15 ID card sample images."""
    images = []
    img_dir = settings.STATIC_DIR / "uploads" / "id_card"
    if img_dir.exists():
        for f in sorted(img_dir.glob("*.*")):
            if f.suffix.lower() in [".jpg", ".jpeg", ".png", ".webp"]:
                url = f"/static/uploads/id_card/{f.name}"
                if url not in images:
                    images.append(url)
    try:
        conn = get_db_connection()
        cursor = conn.cursor()
        cursor.execute("SELECT image_url, gallery_images FROM products WHERE workspace_id = ? AND is_active = 1 AND (category LIKE '%কার্ড%' OR category LIKE '%আইডি%' OR code LIKE '%IDC%')", (int(workspace_id or 1),))
        for p in cursor.fetchall():
            if p["image_url"] and p["image_url"] not in images:
                images.append(p["image_url"])
            try:
                for gu in json.loads(p["gallery_images"] or "[]"):
                    u = gu.get("url") if isinstance(gu, dict) else gu
                    if u and u not in images:
                        images.append(u)
            except Exception:
                pass
        conn.close()
    except Exception:
        pass
    return images

